def mapped_columns(table: str) -> dict[str, str]:
    """返回该表的 {doc_key: column_name}；未扁平化的表返回空 dict。"""
    return COLUMN_MAP.get(table, {})


def column_type(column: str) -> str:
    """返回列的 SQL 类型；未知列按 TEXT 处理（调用方只应传入映射内的列）。"""
    return COLUMN_TYPES.get(column, "TEXT")


def is_jsonb(table: str, column: str) -> bool:
    """该表的这个映射列是否是 JSONB 类型（数组/对象列）。"""
    return COLUMN_TYPES.get(column) == "JSONB"


def readable_columns(table: str) -> list[str]:
    """读路径需要附加 SELECT 的列清单（保序、去重）。"""
    seen: dict[str, None] = {}
    for _key, col in mapped_columns(table).items():
        seen.setdefault(col, None)
    return list(seen)
